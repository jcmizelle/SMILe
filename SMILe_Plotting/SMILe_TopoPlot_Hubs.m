function SMILe_TopoPlot_Hubs(layout, pars, hubs)
%--------------------------------------------------------------------------
%
% This function produces a topographical plot of activation (any type)
% across the electrode montage.
%
% This is an improved version of the EEGLAB topoplot, and mimics the
% FieldTrip version without all of the headache.
%
% Input:
%   datain      - A 1 x nchan vector of data to visualize
%
%   layout      - A channel location structure (FieldTrip format)
%
%   Pars is optional:
%       pars.scale sets the scale of the color map. Either a 1x2 vector
%            corresponding to minimum and a maximum or just a number
%            (say x) then the scale is from [-x x]. The default is
%            scale = [min(z),max(z)];
%       pars.resolution sets the resolution - default is 300
%       pars.cbar = 1 draws colorbar, otherwise colorbar is not shown.
%           Default is 0;
%       pars.cbarsize scales the size of the colorbar by this factor.
%           Default is .9;
%       pars.addcontour = 1 add contour lines to the plot; default is 0
%
%--------------------------------------------------------------------------


%%
%$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$
%$$
%$$$$$$ Set Parameters for the plot
%$$
%$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$

if ~exist('layout', 'var') || isempty(layout)
    try
        load('path/to/templates/64layout.mat')
   
    catch
%--------------------------------------------------------------------------
% I've laid out all of the necessary parameters in a subfunction below:
%--------------------------------------------------------------------------
        [layout] = make_layout();
               
    end
   
end

%--------------------------------------------------------------------------
% Get data and positions of electrodes:
%--------------------------------------------------------------------------
datain = zeros(1,62);
z = datain;
x = layout.pos(:,1);
y = layout.pos(:,2);

%--------------------------------------------------------------------------
% Set defaults:
%--------------------------------------------------------------------------

%--------------------------------------------------------------------------
% Z-axis limits:
%--------------------------------------------------------------------------
scal = [min(z), max(z)];

%--------------------------------------------------------------------------
% Colorbar (binary):
%--------------------------------------------------------------------------
cbar = 0;

%--------------------------------------------------------------------------
% Image resolution:
%--------------------------------------------------------------------------
resolution = 300;

%--------------------------------------------------------------------------
% Color map:
%--------------------------------------------------------------------------
%cmap = 'jet';
cmap = [1 1 1];

%--------------------------------------------------------------------------
% Contour lines:
%--------------------------------------------------------------------------
addContour = 0;

%--------------------------------------------------------------------------
% Color bar size (likely depricated):
%--------------------------------------------------------------------------
cbarsize = .9;

%--------------------------------------------------------------------------
% Handle optional inputs:
%--------------------------------------------------------------------------
if nargin > 2
   
    if isfield(pars,'scale')
        scal = pars.scale;
       
        if length(scal) == 1
            scal = [-scal scal];
            
        elseif length(scal) == 2
            scal = [scal(1) scal(2)];
       
        end
       
    end
   
    if isfield(pars,'cbar')
       cbar = pars.cbar;
   
    end
   
    if isfield(pars,'colorbar')
       cbar = pars.colorbar;
   
    end
   
    if isfield(pars,'resolution')
       resolution = pars.resolution;
   
    end
   
    if isfield(pars,'cmap')
       cmap = pars.cmap;
   
    end
   
    if isfield(pars,'addContour') && ~isempty(pars.addContour) && pars.addContour ~= 0 
       addContour = pars.addContour;
   
    end
    
    if isfield(pars,'cbarsize')
       cbarsize = pars.cbarsize;
   
    end
 
end

%%
%$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$
%$$
%$$$$$$ Start plotting
%$$
%$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$$

%--------------------------------------------------------------------------
% Make axes square, and then shut off feedback:
%--------------------------------------------------------------------------
fh = figure('Units', 'Pixels');
hold on
axis square;
axis off;

%--------------------------------------------------------------------------
% Create the head based on FieldTrip layout:
%--------------------------------------------------------------------------
hold on;

plot(layout.outline{1}(:,1), layout.outline{1}(:,2), 'k', 'LineWidth',4)
plot(layout.outline{1}(:,1), layout.outline{1}(:,2), 'g', 'LineWidth',4, 'color', [119,136,153]./255)
plot(layout.outline{2}(:,1), layout.outline{2}(:,2), '--k', 'LineWidth',4)
plot(layout.outline{2}(:,1), layout.outline{2}(:,2), 'g', 'LineWidth',4, 'color', [119,136,153]./255)
plot(layout.outline{3}(:,1), layout.outline{3}(:,2), '--k', 'LineWidth',4)
plot(layout.outline{3}(:,1), layout.outline{3}(:,2), 'g', 'LineWidth',4, 'color', [119,136,153]./255)
plot(layout.outline{4}(:,1), layout.outline{4}(:,2), '--k', 'LineWidth',4)
plot(layout.outline{4}(:,1), layout.outline{4}(:,2), 'g', 'LineWidth',4, 'color', [119,136,153]./255)

%--------------------------------------------------------------------------
% Format data based on resolution:
%--------------------------------------------------------------------------
xlin = linspace(1.6*min(x), 1.6*max(x), resolution);
ylin = linspace(1.6*min(y), 1.6*max(y), resolution);
[X,Y] = meshgrid(xlin, ylin);

%--------------------------------------------------------------------------
% Interpolate data based on resolution parameters set above - default is
% 'v4', but other options include 'invdist' and 'nearest':
%--------------------------------------------------------------------------
Z = griddata(x, y, z, X, Y, 'v4');

%--------------------------------------------------------------------------
% Create a "mask" and take data from only within the head radius:
%--------------------------------------------------------------------------
rmax = 1.055 * max(sqrt(x.^2+y.^2));
mask = (sqrt(X.^2+Y.^2) <= rmax);
idx = find(mask == 0);
Z(idx) = NaN;

%--------------------------------------------------------------------------
% Add contour lines if requested
%--------------------------------------------------------------------------
if addContour == 1
    numContours = 7;
    contourColor = 'k';
    lineWidth = 2;
    contour(X,Y,Z,numContours,contourColor, 'LineWidth', lineWidth)

end

%--------------------------------------------------------------------------
% Plot the formatted data:
%--------------------------------------------------------------------------
surface(X, Y, zeros(size(Z)), Z, 'edgecolor', 'none');

%--------------------------------------------------------------------------
% Apply selected (or default) color map:
%--------------------------------------------------------------------------
caxis(scal);

%--------------------------------------------------------------------------
% Apply selected (or default) color map:
%--------------------------------------------------------------------------
colormap(cmap);
shading interp;

%--------------------------------------------------------------------------
% Lay down the nodes:
%--------------------------------------------------------------------------
x = layout.pos(:,1);
y = layout.pos(:,2);
plot(x, y, 'ko', 'markersize', 6, 'markerfacecolor', 'k')

% if size(hubs,1) > size(hubs,2)
%     hubs = transpose(hubs);
%     
% end

hubs(hubs == 0) = [];

for numhubs = 1:numel(hubs)
    if hubs(numhubs) ~=0 
        plot(x(hubs(numhubs)), y(hubs(numhubs)), 'r*', 'markersize', 30, 'markerfacecolor', 'r')

    end

end


%--------------------------------------------------------------------------
% Adjust size of the figure and other properties:
%--------------------------------------------------------------------------
set(gcf, 'Position',  [100, 100, 900, 800])

ax = gca;
outerpos = ax.OuterPosition;
ti = ax.TightInset;
left = outerpos(1) + ti(1);
bottom = outerpos(2) + ti(2);
ax_width = outerpos(3) - ti(1) - ti(3);
ax_height = outerpos(4) - ti(2) - ti(4);
ax.Position = [left bottom ax_width ax_height];

%--------------------------------------------------------------------------
% Make background white:
%--------------------------------------------------------------------------
fig = gcf;
fig.Color = [1 1 1];

%--------------------------------------------------------------------------
% Move the whole thing to the center of the screen:
%--------------------------------------------------------------------------
movegui(fig,'center');

%--------------------------------------------------------------------------
% Take care of the colorbar, if one was selected:
%--------------------------------------------------------------------------
if cbar == 1
cbh = colorbar(ax);
set(cbh,'fontweight','bold', 'fontsize', 12);
    cbh.Position([2,4]) = [.22,.55];  
    cbh.Units = fh.Units;
    ax.Units = fh.Units;
   
%--------------------------------------------------------------------------
% Shift axes and position of the colorbar:
%--------------------------------------------------------------------------
    ax.Position(1) = -(ax.Position(3)-ax.Position(4))/2 + 1;
    cbh.Position(1) = sum(ax.Position([1,3])) + ax.Position(1);
    fh.Position(3) = sum(cbh.Position([1,3]))+cbh.Position(3)*5.5;
 
end

