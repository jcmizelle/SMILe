function surr = SMILe_Surrogates_RandPhase_Single(datain,numsurr)
%--------------------------------------------------------------------------
% Inputs:
% data: For this version, a vector of samples to be randomized: 1 x ntimes
% 
% nsurr: The number of desired surrogate data sets
%--------------------------------------------------------------------------
% Output:
% surr: The surrogate data sets in the same dimension as the input data
%-------------------------------------------------------------------------- 
%%
%-------------------------------------------------------------------------- 
% Get information about the size of the data set:
%--------------------------------------------------------------------------
dims = size(datain);
surr = zeros([dims numsurr]);

%--------------------------------------------------------------------------
% Signal properties for the Fourier:
%--------------------------------------------------------------------------
sigleng = length(datain);

%--------------------------------------------------------------------------
% Compute the Fourier transform:
%--------------------------------------------------------------------------
y = fft(datain);

%--------------------------------------------------------------------------
% Get the magnitudes:
%--------------------------------------------------------------------------
m = abs(y);

%--------------------------------------------------------------------------
% Calculate the phase angles:
%--------------------------------------------------------------------------
p = angle(y);

%--------------------------------------------------------------------------
% Compute the imaginary unit:
%--------------------------------------------------------------------------
i = sqrt(-1);

%--------------------------------------------------------------------------
% Work over half of the data points:
%--------------------------------------------------------------------------
h = floor(sigleng/2);

%--------------------------------------------------------------------------
% Loop across surrogates:
%--------------------------------------------------------------------------
for j = 1:numsurr
    
%--------------------------------------------------------------------------
% Randomize the phases:
%--------------------------------------------------------------------------
   if rem(sigleng,2) == 0
      p1 = rand(h-1,1)*2*pi;
      p(2:sigleng) = [p1' p(h+1) -flipud(p1)'];
      
%--------------------------------------------------------------------------
% Adjust the magnitudes:
%--------------------------------------------------------------------------      
      m = [m(1:h+1);flipud(m(2:h))];
   
   else
      p1 = rand(h,1)*2*pi;
      p(2:sigleng) = [p1 -flipud(p1)];
   
   end
   
%--------------------------------------------------------------------------
% Take back to the complex plane:
%--------------------------------------------------------------------------   
   surr(:,j) = m.*exp(i*p);
   
%--------------------------------------------------------------------------
% Return the time series (phase randomized surrogates):
%--------------------------------------------------------------------------
   surr(:,j) = real(ifft(surr(:,j)));
   
end

%--------------------------------------------------------------------------
% End for function:
%--------------------------------------------------------------------------
end