function [surr] = SMILe_Surrogates_AAFT(datain,numsurr)
%--------------------------------------------------------------------------
% Amplitude adjusted Fourier transform with exact distribution
%--------------------------------------------------------------------------
% Inputs:
% data: Typically a nchan x ntimes [x ntrials] matrix
% 
% nsurr: The number of desired surrogate data sets
%--------------------------------------------------------------------------
% Output:
% surr: The surrogate data sets in the same dimension as the input data
%-------------------------------------------------------------------------- 
%%
origdims = size(datain);
ndims = numel(origdims);
if min(origdims) == 1
    ndims = 1;
    
end

if numel(origdims) == 3
    datain = squeeze(mean(datain,3));

end

dims = size(datain);
numchan = dims(1);

if dims(1) > dims(2)
    datain = permute(datain, [2 1]);
    
end

%-------------------------------------------------------------------------- 
% Allocate memory for output:
%-------------------------------------------------------------------------- 
surr = zeros([dims numsurr]);

%--------------------------------------------------------------------------
% Start progress bar:
%--------------------------------------------------------------------------
%wh = waitbar(0,'Starting...');

multiWaitbar( 'Channels', 'Color', [0.8 0.0 0.1] );
multiWaitbar( 'Surrogates', 'Color', [0.2 0.9 0.3] );

%--------------------------------------------------------------------------
% Loop across channels:
%-------------------------------------------------------------------------- 
for nchan = 1:numchan
    %waitbar(nchan/numchan, h, sprintf('Creating surrogate %1.0f of %3.0f ', nchan, numchan))
    
%--------------------------------------------------------------------------
% Update waitbar:
%--------------------------------------------------------------------------
    multiWaitbar( 'Channels', nchan/numchan );
    
%--------------------------------------------------------------------------
% Pull channel data:
%--------------------------------------------------------------------------    
    sig = datain(nchan,:);
    sig = transpose(sig);
    
%--------------------------------------------------------------------------
% Loop across surrogates:
%--------------------------------------------------------------------------    
    for i = 1:numsurr
        
%--------------------------------------------------------------------------
% Update waitbar:
%--------------------------------------------------------------------------        
        multiWaitbar( 'Surrogates', i/numsurr );
        
%--------------------------------------------------------------------------
% Initialize:
%-------------------------------------------------------------------------- 
        y = sig;
        
%--------------------------------------------------------------------------
% Make n normal random devaiates:
%--------------------------------------------------------------------------         
        normal = sort(randn(size(y)));
        
%--------------------------------------------------------------------------
% Sort y and extract the ranks:
%--------------------------------------------------------------------------                 
        [y,T] = sort(y);
        [T,r] = sort(T);
        
%--------------------------------------------------------------------------
% Assign the ranks of y to the normal deviates and apply the phase
% randomization:
%--------------------------------------------------------------------------              
        %normal = SMILe_Surrogates_RandPhase_Single(normal(r),[]);
        normal = SMILe_Surrogates_RandPhase_Single(normal(r),1);
        
%--------------------------------------------------------------------------
% Extract the ranks of the phase randomized normal deviates:
%--------------------------------------------------------------------------
        [normal,T] = sort(normal);
        [T,r] = sort(T);
        
%--------------------------------------------------------------------------
% Assign the ranks of the phase randomized normal deviates to y and obtain 
% the AAFT surrogates:
%--------------------------------------------------------------------------        
        surr(nchan,:,i) = y(r);
        
%--------------------------------------------------------------------------
% End for surrogates:
%--------------------------------------------------------------------------     
    end
    
%--------------------------------------------------------------------------
% End for channels:
%--------------------------------------------------------------------------    
end

%--------------------------------------------------------------------------
% Kill progress bar:
%--------------------------------------------------------------------------
multiWaitbar('CloseAll');

%--------------------------------------------------------------------------
% End for function:
%--------------------------------------------------------------------------    
end