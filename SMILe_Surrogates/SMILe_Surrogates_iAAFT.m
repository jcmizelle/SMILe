function [surr] = SMILe_Surrogates_iAAFT(datain, numsurr, maxiter)
%--------------------------------------------------------------------------
% Iterated amplitude adjusted Fourier transform with exact distribution
%--------------------------------------------------------------------------
% Inputs:
% data: Typically a nchan x ntimes [x ntrials] matrix
% 
% nsurr: The number of desired surrogate data sets
%--------------------------------------------------------------------------
% Output:
% surr: The surrogate data sets in the same dimension as the input data
%-------------------------------------------------------------------------- 
%%
%-------------------------------------------------------------------------- 
% Get information about the size of the data set:
%-------------------------------------------------------------------------- 
origdims = size(datain);
ndims = numel(origdims);
if min(origdims) == 1
    ndims = 1;
    
end

if numel(origdims) == 3
    datain = squeeze(mean(datain,3));

end

dims = size(datain);
numchan = dims(1);

if dims(1) > dims(2)
    datain = permute(datain, [2 1]);
    
end

%-------------------------------------------------------------------------- 
% Check iterations:
%--------------------------------------------------------------------------
if ~exist('maxiter','var') || isempty(maxiter)
    maxiter = 100;
    
end

%-------------------------------------------------------------------------- 
% Check number of surrogates:
%--------------------------------------------------------------------------
if ~exist('numsurr','var') || isempty(numsurr)
    numsurr = 1000;
    
end

%-------------------------------------------------------------------------- 
% Allocate memory for output:
%-------------------------------------------------------------------------- 
surr = zeros([dims numsurr]);

%--------------------------------------------------------------------------
% Start progress bar:
%--------------------------------------------------------------------------
%wh = waitbar(0,'Starting...');

multiWaitbar( 'Channels', 'Color', [0.8 0.0 0.1] );
multiWaitbar( 'Surrogates', 'Color', [0.2 0.9 0.3] );

%--------------------------------------------------------------------------
% Loop across channels:
%--------------------------------------------------------------------------
for nchan = 1:numchan
    
%--------------------------------------------------------------------------
% Update waitbar:
%--------------------------------------------------------------------------
    multiWaitbar( 'Channels', nchan/numchan );
    
%--------------------------------------------------------------------------
% Pull channel data:
%--------------------------------------------------------------------------    
    sig = datain(nchan,:);
    sig = transpose(sig);

%--------------------------------------------------------------------------
% Fourier transform of the data:
%-------------------------------------------------------------------------- 
    fftamp = abs(fft(sig));

%-------------------------------------------------------------------------- 
% Shuffle the signal:
%-------------------------------------------------------------------------- 
    surrog = SMILe_Shuffle(sig,numsurr);

%-------------------------------------------------------------------------- 
% Shuffle the signal:
%--------------------------------------------------------------------------     
    [sig,r] = sort(sig);

    for j = 1:numsurr

%--------------------------------------------------------------------------
% Update waitbar:
%--------------------------------------------------------------------------        
        multiWaitbar( 'Surrogates', j/numsurr );
        
%-------------------------------------------------------------------------- 
% Calculate the phases of the shuffled series:
%--------------------------------------------------------------------------     
        phase = angle(fft(surrog(:,j)));

%-------------------------------------------------------------------------- 
% Initialize the loop:
%--------------------------------------------------------------------------    
        k = 1;
        indold = r;
        converge = 0;
        
        while k <= maxiter && converge == 0 

%-------------------------------------------------------------------------- 
% Make phase-randomized surrogates
%--------------------------------------------------------------------------        
            surrog(:,j) = fftamp.*exp(phase.*1i); 
            surrog(:,j) = real(ifft(surrog(:,j)));

%-------------------------------------------------------------------------- 
% ...and give them the distribution of the signal:
%--------------------------------------------------------------------------           
            [surrog(:,j),T] = sort(surrog(:,j));
            [surrog(:,j),indnew] = sort(T);
            surrog(:,j) = sig(indnew);

%-------------------------------------------------------------------------- 
% Check the convergence:
%--------------------------------------------------------------------------         
            if indnew == indold
                converge = 1;

            else
                indold = indnew;
                k = k+1;

            end
            
%--------------------------------------------------------------------------
% Loop again if needed, calculating the phases once more:
%--------------------------------------------------------------------------  
            phase = angle(fft(surrog(:,j)));

        end

%-------------------------------------------------------------------------- 
% End surrogate loop, collect surrogates:
%--------------------------------------------------------------------------         
    end

surr(nchan,:,:) = squeeze(surrog);

%-------------------------------------------------------------------------- 
% End channel loop:
%--------------------------------------------------------------------------             
end
 
%--------------------------------------------------------------------------
% Kill progress bar:
%--------------------------------------------------------------------------
%close(wh)
multiWaitbar('CloseAll');

%-------------------------------------------------------------------------- 
% End for function:
%--------------------------------------------------------------------------
end